#!/bin/sh
# Прогон на сервере: догнать репозиторий, затем прогон с публикацией.
#
# Серверный клон -- не место для работы, только для прогона. Всё, что в нём не
# закоммичено, -- это результат прерванного прошлого прогона, который ничего не
# опубликовал. Его выбрасываем: прогон соберёт всё заново, а объявления у
# источников никуда не денутся. Игнорируемые файлы (резервации id, логи) не
# трогаются: git clean без -x их не удаляет.
#
# Сессия на ПК владельца тоже пушит -- строки из Facebook и Telegram. Поэтому
# прогон всегда начинается с origin/main: иначе его пуш упёрся бы в чужой коммит.
set -eu
cd /opt/rentsearcher/app
git fetch -q origin
git reset -q --hard origin/main
git clean -fdq
exec /usr/bin/python3 run_pipeline.py --publish --no-fb --no-tg
